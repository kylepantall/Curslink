"""The overlay helper's side of clipboard sync (runs in the Qt helper).

Commands it takes (see :mod:`curslink.overlay`)::

    clipwatch on                 start telling the service what's copied here
    clipwatch off                stop
    clipset {"kind": "text", "text": "..."}
    clipset {"kind": "image", "path": "/tmp/.../clipboard.png"}
    clipset {"kind": "files", "paths": ["/tmp/.../report.pdf", ...]}
                                 put what another device copied on this
                                 one's clipboard

What it prints when something new is copied here::

    clip {"kind": "text", "text": "..."}
    clip {"kind": "image", "path": "<a PNG it wrote; the service removes it>"}
    clip {"kind": "files", "paths": ["/Users/me/report.pdf", ...]}

Qt's ``dataChanged`` signal tells it about changes on Windows and Linux.
On macOS Qt only notices them when its app becomes active, which the
helper (an accessory app) never does, so there it also polls the
pasteboard's change count.

What it put there itself isn't reported back (that would bounce between
devices): it remembers what it set, and treats the next change of the
same kind within a moment of setting as its own too, as some platforms
hand an image back a little different from how it went in.
"""

from __future__ import annotations

import hashlib
import json
import logging
import os
import sys
import tempfile
import time

log = logging.getLogger(__name__)

# Formats that mark a copy as private or passing (password managers).
PRIVATE_MARKERS = (
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "ExcludeClipboardContentFromMonitorProcessing",
    "CanIncludeInClipboardHistory",
    "x-kde-passwordManagerHint",
)
# Windows formats that carry a DWORD saying yes or no: only 0 means "keep this
# out of clipboard history / the cloud". Snipping Tool and others write 1 (yes,
# share it), so their mere presence doesn't make a copy private.
YES_NO_MARKERS = ("CanIncludeInClipboardHistory",)
OWN_CHANGE_S = 1.5
SETTLE_MS = 150
MAC_POLL_MS = 300


def private_marker(formats, read=None) -> str | None:
    """The marker that makes a copy private (password managers), or None.
    ``read(format)`` gives a format's bytes, for the yes/no markers; without
    it they count as private."""
    for f in formats:
        for marker in PRIVATE_MARKERS:
            if marker not in str(f):
                continue
            if marker in YES_NO_MARKERS and read is not None:
                try:
                    raw = bytes(read(f))
                except Exception:  # pragma: no cover - a platform clipboard quirk
                    raw = b""
                if len(raw) >= 4 and int.from_bytes(raw[:4], "little") != 0:
                    continue  # "yes, this may be shared"
            return marker
    return None


def is_private(formats, read=None) -> bool:
    return private_marker(formats, read) is not None


def text_sig(text: str) -> tuple[str, str]:
    return ("text", hashlib.sha1(text.encode("utf-8", "surrogatepass")).hexdigest())


def files_sig(paths: list[str]) -> tuple[str, str]:
    return ("files", "\n".join(os.path.normcase(os.path.realpath(p)) for p in paths))


def image_sig(image) -> tuple[str, str]:
    from PySide6.QtGui import QImage

    img = image.convertToFormat(QImage.Format.Format_ARGB32)
    return ("image", hashlib.sha1(bytes(img.constBits())).hexdigest())


def _say(line: str) -> None:
    try:
        sys.stdout.write(line + "\n")
        sys.stdout.flush()
    except (OSError, ValueError, AttributeError):
        pass


def _mac_change_count():
    """A function returning the pasteboard's change count (macOS), or None."""
    if sys.platform != "darwin":
        return None
    try:
        from AppKit import NSPasteboard
    except ImportError:
        return None
    board = NSPasteboard.generalPasteboard()
    return lambda: int(board.changeCount())


class ClipboardHelper:
    """Watches and sets this device's clipboard, inside the Qt helper."""

    def __init__(self) -> None:
        self.watching = False
        self.clipboard = None
        self.last: tuple[str, str] | None = None  # what's on the clipboard, as far as we know
        self.set_at = 0.0
        self.set_kind = ""
        self.settle = None
        self.poll = None
        self.count = None
        self.last_count = None
        self.folder: str | None = None

    def handle(self, line: str) -> bool:
        word, _, rest = line.strip().partition(" ")
        if word == "clipwatch":
            self.watch(rest.strip() != "off")
        elif word == "clipset":
            try:
                data = json.loads(rest)
            except ValueError:
                return True
            if isinstance(data, dict):
                self.set(data)
        else:
            return False
        return True

    # ------------------------------------------------------------ watching
    def _setup(self) -> None:
        if self.clipboard is not None:
            return
        from PySide6.QtCore import QTimer
        from PySide6.QtGui import QGuiApplication

        self.clipboard = QGuiApplication.clipboard()
        self.settle = QTimer()
        self.settle.setSingleShot(True)
        self.settle.setInterval(SETTLE_MS)
        self.settle.timeout.connect(self.read)
        self.clipboard.dataChanged.connect(self.changed)
        self.count = _mac_change_count()
        if self.count is not None:
            self.last_count = self.count()
            self.poll = QTimer()
            self.poll.setInterval(MAC_POLL_MS)
            self.poll.timeout.connect(self._poll)

    def watch(self, on: bool) -> None:
        self._setup()
        if on and not self.watching:
            # What's there already was copied before we started: not news.
            self.last = self._current_sig()
        self.watching = on
        if self.poll is not None:
            (self.poll.start if on else self.poll.stop)()

    def _poll(self) -> None:
        n = self.count()
        if n != self.last_count:
            self.last_count = n
            self.changed()

    def changed(self) -> None:
        if self.watching and self.settle is not None:
            self.settle.start()  # apps often put a copy's formats there one at a time

    def _current_sig(self):
        try:
            return self._read_mime()[0]
        except Exception:  # pragma: no cover - a platform clipboard quirk
            return None

    def _read_mime(self):
        """(signature, what to report) of the clipboard now, or (None, None)."""
        mime = self.clipboard.mimeData()
        if mime is None:
            return None, None
        marker = private_marker(mime.formats(), lambda f: mime.data(f).data())
        if marker is not None:
            return ("private", marker), None
        if mime.hasUrls():
            paths = [u.toLocalFile() for u in mime.urls() if u.isLocalFile()]
            paths = [p for p in paths if p and os.path.exists(p)]
            if paths:
                return files_sig(paths), {"kind": "files", "paths": paths}
        if mime.hasImage():
            image = self.clipboard.image()
            if not image.isNull():
                return image_sig(image), {"kind": "image", "image": image}
        if mime.hasText():
            text = mime.text()
            if text:
                return text_sig(text), {"kind": "text", "text": text}
        return None, None

    def read(self) -> None:
        if not self.watching:
            return
        try:
            sig, data = self._read_mime()
        except Exception:  # pragma: no cover - a platform clipboard quirk
            log.exception("clipboard: reading it")
            return
        if sig is None or sig == self.last:
            return
        own = time.monotonic() - self.set_at < OWN_CHANGE_S and sig[0] == self.set_kind
        self.last = sig
        if sig[0] == "private":
            _say(f"log clipboard: not sharing a copy marked private ({sig[1]})")
            return
        if own or data is None:
            return
        if data["kind"] == "image":
            path = self._image_path()
            if not data.pop("image").save(path, "PNG"):
                _say("log clipboard: couldn't save the copied image to share it")
                return
            data["path"] = path
        _say("clip " + json.dumps(data, ensure_ascii=True, separators=(",", ":")))

    def _image_path(self) -> str:
        if self.folder is None or not os.path.isdir(self.folder):
            self.folder = tempfile.mkdtemp(prefix="curslink-copied-")
        return os.path.join(self.folder, f"{int(time.time() * 1000)}.png")

    # ------------------------------------------------------------- setting
    def set(self, data: dict) -> None:
        self._setup()
        kind = data.get("kind")
        if kind == "text" and isinstance(data.get("text"), str):
            self._mark(text_sig(data["text"]))
            self.clipboard.setText(data["text"])
        elif kind == "image" and isinstance(data.get("path"), str):
            from PySide6.QtGui import QImage

            image = QImage(data["path"])
            if image.isNull():
                _say(f"log clipboard: couldn't read the image to paste ({data['path']})")
                return
            self._mark(image_sig(image))
            self.clipboard.setImage(image)
            _say(f"log clipboard: image {image.width()}x{image.height()} ready to paste")
        elif kind == "files" and isinstance(data.get("paths"), list):
            from PySide6.QtCore import QMimeData, QUrl

            paths = [p for p in data["paths"] if isinstance(p, str)]
            mime = QMimeData()
            mime.setUrls([QUrl.fromLocalFile(p) for p in paths])
            self._mark(files_sig(paths))
            self.clipboard.setMimeData(mime)
        else:
            return
        self._render_now()

    def _render_now(self) -> None:
        """Windows: Qt only promises what it put on the clipboard and draws
        it when an app pastes, by calling back into this helper. Hand it all
        to the system now, so a paste works while the helper is busy, and
        after it has restarted or gone."""
        if sys.platform != "win32" or self.clipboard is None:
            return
        try:
            import ctypes

            hr = ctypes.windll.ole32.OleFlushClipboard()
        except (OSError, AttributeError):
            return
        if hr != 0:
            _say(f"log clipboard: Windows didn't take the clipboard's contents (0x{hr & 0xFFFFFFFF:08x})")

    def flush(self) -> None:
        """The helper is leaving: on Windows, hand what we put on the
        clipboard over to the system so it can still be pasted."""
        if sys.platform == "win32" and self.clipboard is not None and self.clipboard.ownsClipboard():
            try:
                import ctypes

                ctypes.windll.ole32.OleFlushClipboard()
            except (OSError, AttributeError):
                pass

    def _mark(self, sig: tuple[str, str]) -> None:
        self.last = sig
        self.set_kind = sig[0]
        self.set_at = time.monotonic()
